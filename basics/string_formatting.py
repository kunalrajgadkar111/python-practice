# Expressions inside f-strings
a = 10
b = 20

print(f"{a} + {b} = {a + b}")
print(f"{a} * {b} = {a * b}")

# Formatting decimals
price = 1250.5678
print(f"Price: ₹{price:.2f}")

# Multiple values
name = "Kunal"
skill = "Python"
experience = 0

print(f"My name is {name}, I am learning {skill}, and my experience is {experience} years.")